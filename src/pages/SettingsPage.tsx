import { useRef, useState } from 'react';
import { usePreferences, useProgress } from '../hooks/useProgress';
import { useSpeech } from '../hooks/useSpeech';
import { useDocumentTitle } from '../hooks/useDocumentTitle';
import { describeSpeechStatus } from '../services/speech';
import { parseProgressJson, serializeProgress } from '../services/progressStore';
import { DisplayToggles } from '../components/layout/DisplayToggles';
import { AudioButton } from '../components/learning/AudioButton';
import type { Preferences } from '../domain/progress';

export function SettingsPage() {
  useDocumentTitle('Settings');
  const prefs = usePreferences();
  const { progress, updatePreferences, resetProgress, replaceProgress } = useProgress();
  const { status, voices } = useSpeech();
  const [confirmReset, setConfirmReset] = useState(false);
  const [message, setMessage] = useState<string | null>(null);
  const fileRef = useRef<HTMLInputElement>(null);

  const exportProgress = () => {
    const blob = new Blob([serializeProgress(progress)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `korean-learning-progress-${new Date().toISOString().slice(0, 10)}.json`;
    a.click();
    URL.revokeObjectURL(url);
    setMessage('Progress exported.');
  };

  const importProgress = async (file: File) => {
    const parsed = parseProgressJson(await file.text());
    if (!parsed) {
      setMessage('That file is not a valid progress export. Nothing was changed.');
      return;
    }
    replaceProgress(parsed);
    setMessage('Progress imported.');
  };

  return (
    <div className="page settings">
      <h1>Settings</h1>

      <section className="card" aria-labelledby="display-settings">
        <h2 id="display-settings" className="card__title">
          Display
        </h2>
        <p className="muted">Hide romanization or English to test yourself. Hidden English can be revealed per sentence.</p>
        <DisplayToggles />
        <fieldset className="radio-group">
          <legend>Theme</legend>
          {(['system', 'light', 'dark'] as const).map((t) => (
            <label key={t} className="radio">
              <input type="radio" name="theme" value={t} checked={prefs.theme === t} onChange={() => updatePreferences({ theme: t })} />
              {t === 'system' ? 'Match system' : t === 'light' ? 'Light' : 'Dark'}
            </label>
          ))}
        </fieldset>
      </section>

      <section className="card" aria-labelledby="audio-settings">
        <h2 id="audio-settings" className="card__title">
          Pronunciation audio
        </h2>
        <p role="status">{describeSpeechStatus(status)}</p>
        <p className="muted small">
          Audio is generated by your browser’s text-to-speech engine, not recorded by native speakers. Speech never plays
          automatically, and speaking one item stops any other.
        </p>
        <fieldset className="radio-group">
          <legend>Default speed</legend>
          {(['normal', 'slow'] as Preferences['speechRate'][]).map((r) => (
            <label key={r} className="radio">
              <input type="radio" name="rate" value={r} checked={prefs.speechRate === r} onChange={() => updatePreferences({ speechRate: r })} />
              {r === 'normal' ? 'Normal' : 'Slower (for study)'}
            </label>
          ))}
        </fieldset>
        {voices.length > 1 && (
          <label className="filter">
            <span className="field-label">Korean voice</span>
            <select
              className="text-input"
              value={prefs.voiceURI ?? ''}
              onChange={(e) => updatePreferences({ voiceURI: e.target.value || null })}
            >
              <option value="">Browser default</option>
              {voices.map((v) => (
                <option key={v.voiceURI} value={v.voiceURI}>
                  {v.name} ({v.lang})
                </option>
              ))}
            </select>
          </label>
        )}
        <p className="sample">
          Try it: <span lang="ko">안녕하세요</span> <span className="muted">(annyeonghaseyo, hello)</span>{' '}
          <AudioButton text="안녕하세요" label="안녕하세요" />
        </p>
      </section>

      <section className="card" aria-labelledby="data-settings">
        <h2 id="data-settings" className="card__title">
          Your data
        </h2>
        <p>
          Progress is stored only in this browser (localStorage). Nothing is sent to a server. Clearing site data or switching
          devices will lose it unless you export a backup.
        </p>
        <div className="button-row">
          <button type="button" className="button" onClick={exportProgress}>
            Export progress (JSON)
          </button>
          <button type="button" className="button" onClick={() => fileRef.current?.click()}>
            Import progress
          </button>
          <input
            ref={fileRef}
            type="file"
            accept="application/json,.json"
            className="visually-hidden"
            tabIndex={-1}
            aria-hidden="true"
            onChange={(e) => {
              const file = e.target.files?.[0];
              if (file) void importProgress(file);
              e.target.value = '';
            }}
          />
        </div>
        <div className="danger-zone">
          {!confirmReset ? (
            <button type="button" className="button button--danger" onClick={() => setConfirmReset(true)}>
              Reset learning progress…
            </button>
          ) : (
            <div role="alertdialog" aria-labelledby="reset-title" className="confirm">
              <p id="reset-title">
                <strong>Reset all lesson progress, quiz results, and saved words?</strong> Display settings are kept. This
                cannot be undone.
              </p>
              <div className="button-row">
                <button
                  type="button"
                  className="button button--danger"
                  onClick={() => {
                    resetProgress();
                    setConfirmReset(false);
                    setMessage('Progress reset.');
                  }}
                >
                  Yes, reset
                </button>
                <button type="button" className="button" onClick={() => setConfirmReset(false)} autoFocus>
                  Cancel
                </button>
              </div>
            </div>
          )}
        </div>
        <p role="status" className="muted">
          {message}
        </p>
      </section>
    </div>
  );
}
